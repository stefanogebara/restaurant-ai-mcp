#!/usr/bin/env node
/**
 * One-off repair for Seatable agents created in English while their saved
 * restaurant language and default greeting were Portuguese, Italian or Spanish.
 *
 * Inventory: node scripts/migrate-elevenlabs-agent-language.cjs --project-ref ckforlwdhewexyqljsaf
 * Canary:    node scripts/migrate-elevenlabs-agent-language.cjs --project-ref ckforlwdhewexyqljsaf --only-agent AGENT_ID --apply --manifest /secure/path/canary.jsonl
 * Batch:     node scripts/migrate-elevenlabs-agent-language.cjs --project-ref ckforlwdhewexyqljsaf --apply --manifest /secure/path/batch.jsonl
 *
 * Requires SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY and ELEVENLABS_API_KEY.
 * Apply journals contain the previous language and first message for rollback.
 */
'use strict';

const {
  PROJECT_REF, SUPABASE_URL, WORKSPACE_ID, assertProject, assertWorkspace, createJournal,
} = require('./migrate-elevenlabs-date-tools.cjs');

const BASE = 'https://api.elevenlabs.io/v1';
const LOCAL_DEFAULTS = {
  pt: name => `Obrigado por ligar para ${name}! Como posso ajudá-lo hoje?`,
  it: name => `Grazie per aver chiamato ${name}! Come posso aiutarla oggi?`,
  es: name => `¡Gracias por llamar a ${name}! ¿Cómo puedo ayudarle hoy?`,
};
// Keep this identical to the greeting originally generated by createAgent.
const ENGLISH_DEFAULT = name => `Thank you for calling ${name}. How may I help you today?`;

function parseArgs(argv) {
  const opts = { projectRef: null, apply: false, manifest: null, onlyAgent: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--project-ref' && argv[i + 1]) opts.projectRef = argv[++i];
    else if (argv[i] === '--only-agent' && argv[i + 1]) opts.onlyAgent = argv[++i];
    else if (argv[i] === '--manifest' && argv[i + 1]) opts.manifest = argv[++i];
    else if (argv[i] === '--apply') opts.apply = true;
    else throw new Error(`Unknown or incomplete argument: ${argv[i]}`);
  }
  if (opts.apply && !opts.manifest) throw new Error('--apply requires --manifest');
  if (!opts.apply && opts.manifest) throw new Error('--manifest requires --apply');
  return opts;
}

function inspect(row, agent) {
  if (row?.is_active !== true || row?.is_demo !== false || !row?.id || !row?.elevenlabs_agent_id ||
      !row?.restaurant_name) return { status: 'skip', reason: 'ineligible_row' };
  if (row.agent_greeting) return { status: 'skip', reason: 'custom_greeting' };
  const targetLanguage = row.agent_language;
  if (!Object.hasOwn(LOCAL_DEFAULTS, targetLanguage) ||
      row.ai_config?.language?.split('-')[0] !== targetLanguage) {
    return { status: 'skip', reason: 'config_language_mismatch' };
  }
  const targetGreeting = LOCAL_DEFAULTS[targetLanguage](row.restaurant_name);
  if (row.ai_config?.greeting_message !== targetGreeting) {
    return { status: 'skip', reason: 'custom_config_greeting' };
  }
  const current = agent?.conversation_config?.agent;
  if (current?.language !== 'en') return { status: 'skip', reason: 'provider_not_english' };
  if (current.first_message !== ENGLISH_DEFAULT(row.restaurant_name)) {
    return { status: 'skip', reason: 'nondefault_first_message' };
  }
  // ElevenLabs rejects non-English languages with flash v2. The model change
  // must be in the same PATCH as language so no intermediate config is invalid.
  const oldTtsModel = agent?.conversation_config?.tts?.model_id;
  if (oldTtsModel !== 'eleven_flash_v2' && oldTtsModel !== 'eleven_flash_v2_5') {
    return { status: 'skip', reason: 'unsupported_tts_model' };
  }
  return { status: 'ready', targetLanguage, targetGreeting, targetTtsModel: 'eleven_flash_v2_5' };
}

async function inventory({ db, api }) {
  const rows = await db.listRows();
  if (!Array.isArray(rows)) throw new Error('Restaurant inventory unavailable');
  const counts = new Map();
  for (const row of rows) counts.set(row.elevenlabs_agent_id, (counts.get(row.elevenlabs_agent_id) || 0) + 1);
  const items = [];
  for (const row of rows) {
    if (counts.get(row.elevenlabs_agent_id) !== 1) {
      items.push({ row, status: 'skip', reason: 'shared_agent' });
      continue;
    }
    const agent = await api.getAgent(row.elevenlabs_agent_id);
    items.push({ row, agent, ...inspect(row, agent) });
  }
  return items;
}

async function migrate({ items, db, api, journal = () => {} }) {
  const report = [];
  for (const item of items.filter(x => x.status === 'ready')) {
    const id = item.row.elevenlabs_agent_id;
    // Recheck both systems after inventory, before writing a recovery record.
    const [row, agent] = await Promise.all([db.getRow(item.row.id), api.getAgent(id)]);
    const fresh = inspect(row, agent);
    const oldConfig = item.agent?.conversation_config?.agent;
    const current = agent?.conversation_config?.agent;
    const oldTtsModel = item.agent?.conversation_config?.tts?.model_id;
    const currentTtsModel = agent?.conversation_config?.tts?.model_id;
    if (row?.elevenlabs_agent_id !== id || fresh.status !== 'ready' ||
        fresh.targetLanguage !== item.targetLanguage || fresh.targetGreeting !== item.targetGreeting ||
        current?.language !== oldConfig?.language || current?.first_message !== oldConfig?.first_message ||
        currentTtsModel !== oldTtsModel ||
        agent?.version_id !== item.agent?.version_id) {
      throw new Error(`Agent ${id} changed after inventory; no write attempted`);
    }
    const updates = {
      agent: { language: item.targetLanguage, first_message: item.targetGreeting },
      tts: { model_id: item.targetTtsModel },
    };
    const rollback = {
      agent_id: id, old_language: current.language, old_first_message: current.first_message,
      old_tts_model: oldTtsModel,
      new_language: updates.agent.language, new_first_message: updates.agent.first_message,
      new_tts_model: updates.tts.model_id,
    };
    journal({ ...rollback, state: 'patch_intent' });
    try {
      await api.patchAgent(id, updates);
      journal({ ...rollback, state: 'patch_returned' });
      const saved = await api.getAgent(id);
      if (saved?.conversation_config?.agent?.language !== updates.agent.language ||
          saved?.conversation_config?.agent?.first_message !== updates.agent.first_message ||
          saved?.conversation_config?.tts?.model_id !== updates.tts.model_id) {
        throw new Error('Provider readback mismatch');
      }
      journal({ ...rollback, new_version_id: saved.version_id || null, state: 'verified' });
      report.push({ agentId: id, status: 'verified' });
    } catch (error) {
      try { journal({ ...rollback, state: 'failed' }); } catch { /* preserve original failure */ }
      throw new Error(`Language migration stopped at ${id}; inspect the rollback journal and provider version`);
    }
  }
  return report;
}

function createApi(apiKey, fetcher = fetch) {
  const headers = { 'xi-api-key': apiKey, 'Content-Type': 'application/json' };
  async function request(path, method = 'GET', body) {
    const res = await fetcher(`${BASE}${path}`, {
      method, headers, ...(body ? { body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(15_000),
    });
    if (!res.ok) throw new Error(`ElevenLabs ${method} failed: HTTP ${res.status}`);
    return res.json();
  }
  return {
    getWorkspaceId: async () => (await request('/user')).workspace_id,
    getAgent: id => request(`/convai/agents/${encodeURIComponent(id)}`),
    patchAgent: (id, updates) => request(`/convai/agents/${encodeURIComponent(id)}`, 'PATCH', {
      conversation_config: updates,
    }),
  };
}

function createDb(client) {
  const columns = 'id,is_active,is_demo,restaurant_name,elevenlabs_agent_id,agent_language,ai_config,agent_greeting';
  const table = () => client.schema('restaurant').from('restaurant_config');
  return {
    async listRows() {
      const rows = [];
      for (let start = 0; ; start += 500) {
        const { data, error } = await table().select(columns)
          .eq('is_active', true).eq('is_demo', false).not('elevenlabs_agent_id', 'is', null)
          .order('id').range(start, start + 499);
        if (error) throw new Error(`Restaurant inventory failed: ${error.message}`);
        rows.push(...data);
        if (data.length < 500) return rows;
      }
    },
    async getRow(id) {
      const { data, error } = await table().select(columns).eq('id', id).maybeSingle();
      if (error) throw new Error(`Restaurant recheck failed: ${error.message}`);
      return data;
    },
  };
}

async function main(argv = process.argv.slice(2), env = process.env) {
  const opts = parseArgs(argv);
  assertProject(opts.projectRef, env.SUPABASE_URL);
  if (!env.SUPABASE_SERVICE_ROLE_KEY || !env.ELEVENLABS_API_KEY) throw new Error('Required credentials missing');
  const { createClient } = require('@supabase/supabase-js');
  const db = createDb(createClient(SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } }));
  const api = createApi(env.ELEVENLABS_API_KEY);
  assertWorkspace(WORKSPACE_ID, await api.getWorkspaceId());
  const items = await inventory({ db, api });
  const selected = opts.onlyAgent ? items.filter(x => x.row.elevenlabs_agent_id === opts.onlyAgent) : items;
  if (opts.onlyAgent && selected.length !== 1) throw new Error('Canary agent not found uniquely');
  for (const item of selected) console.log(JSON.stringify({ agent_id: item.row.elevenlabs_agent_id, status: item.status, reason: item.reason }));
  if (!opts.apply) return;
  if (opts.onlyAgent && selected[0].status !== 'ready') throw new Error('Canary agent is not eligible');
  const file = createJournal(opts.manifest);
  try {
    const report = await migrate({ items: selected, db, api, journal: entry => file.append(entry) });
    console.log(JSON.stringify({ verified: report.length }));
  } finally { file.close(); }
}

if (require.main === module) {
  require('dotenv').config();
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}

module.exports = { assertProject, assertWorkspace, parseArgs, inspect, inventory, migrate, createApi, createDb, main };
